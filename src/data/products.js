export const getBackendProductById = (id) => {
  return backendProducts.find((product) => product._id === id);
};

export const mapBackendProductToUi = (product) => {
  return {
    id: product._id,
    name: product.nome,
    description: product.descricao,
    price: product.valor_final ?? product.valor,
    originalPrice: product.valor,
    discount: product.desconto ?? 0,
    image: product.image_url || "/images/product-placeholder.jpg",
  };
};

export const getBackendProductsByName = (name) => {
  const normalizedName = name.trim().toLowerCase();
  return backendProducts.filter(
    (product) => product.nome.trim().toLowerCase() === normalizedName
  );
};

export const getBackendProductGroupById = (id) => {
  const selectedProduct = getBackendProductById(id);

  if (!selectedProduct) {
    return {
      selectedProduct: null,
      variants: [],
    };
  }

  const variants = getBackendProductsByName(selectedProduct.nome);

  return {
    selectedProduct,
    variants,
  };
};

export const getVariantSizes = (variants) => {
  return [...new Set(variants.map((variant) => variant.tamanho).filter(Boolean))];
};

export const getVariantColors = (variants) => {
  return [...new Set(variants.map((variant) => variant.cor).filter(Boolean))];
};

export const getClosestVariant = (variants, size, color) => {
  return (
    variants.find(
      (variant) => variant.tamanho === size && variant.cor === color
    ) ||
    variants.find((variant) => variant.tamanho === size) ||
    variants.find((variant) => variant.cor === color) ||
    variants[0] ||
    null
  );
};

export const getFeaturedBackendProducts = () => {
  const seenNames = new Set();

  return backendProducts.filter((product) => {
    const hasDiscount = Number(product.desconto) > 0;
    if (!hasDiscount) return false;

    const normalizedName = product.nome.trim().toLowerCase();

    if (seenNames.has(normalizedName)) {
      return false;
    }

    seenNames.add(normalizedName);
    return true;
  });
};

export const getFeaturedProductsUi = () => {
  return getFeaturedBackendProducts().map(mapBackendProductToUi);
};

export const getUniqueBackendProductsByName = () => {
  const seenNames = new Set();

  return backendProducts.filter((product) => {
    const normalizedName = product.nome.trim().toLowerCase();

    if (seenNames.has(normalizedName)) {
      return false;
    }

    seenNames.add(normalizedName);
    return true;
  });
};

export const getUniqueProductsUi = () => {
  return getUniqueBackendProductsByName().map(mapBackendProductToUi);
};